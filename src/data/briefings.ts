export type BlockType =
  | "text"
  | "warning"
  | "info"
  | "video"
  | "task_match"   // сопоставление пар
  | "task_sort"    // выбрать правильные из списка
  | "task_quiz";   // одиночный вопрос с объяснением

export interface TextBlock {
  type: "text";
  title?: string;
  content: string;
}

export interface WarningBlock {
  type: "warning";
  title: string;
  content: string;
}

export interface InfoBlock {
  type: "info";
  title: string;
  content: string;
}

export interface VideoBlock {
  type: "video";
  title: string;
  youtubeId: string;
  duration: string;
  description: string;
}

export interface TaskMatchBlock {
  type: "task_match";
  title: string;
  instruction: string;
  pairs: { left: string; right: string }[];
}

export interface TaskSortBlock {
  type: "task_sort";
  title: string;
  instruction: string;
  items: { text: string; correct: boolean }[];
}

export interface TaskQuizBlock {
  type: "task_quiz";
  title: string;
  question: string;
  options: string[];
  correct: number;
  explanation: string;
}

export type Block =
  | TextBlock
  | WarningBlock
  | InfoBlock
  | VideoBlock
  | TaskMatchBlock
  | TaskSortBlock
  | TaskQuizBlock;

export interface BriefingVariant {
  id: string;
  label: string;
  blocks: Block[];
}

export interface BriefingData {
  id: string;
  title: string;
  subtitle: string;
  duration: number;
  required: boolean;
  variants?: BriefingVariant[];
  blocks?: Block[];
}

